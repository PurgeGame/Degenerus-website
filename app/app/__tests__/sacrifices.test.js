test('a missing history route degrades to UNAVAILABLE, never to an empty history', async () => {
  // The indexer publishes /api/game/protocol-boon-draws independently of this build,
  // so a 404 means the surface is not up yet. Reporting that as "no entries" would
  // tell a player who just made a hero bet that nothing happened.
  const priorFetch = globalThis.fetch;
  const requested = [];
  try {
    globalThis.fetch = async (url) => {
      requested.push(String(url));
      return { ok: false, status: 404, headers: { get: () => 'application/json' }, json: async () => ({}), text: async () => '' };
    };
    const missing = await readSacrificeHistory(DONOR);
    assert.deepEqual(missing, { available: false, entries: [], awards: [] });
    // The indexer registers these under `/game`, NOT `/api/game` — a wrong prefix is
    // indistinguishable from "route not deployed" and would silently stay empty forever.
    assert.ok(requested.some((url) => url.includes('/game/protocol-boon-draws')
      && !url.includes('/api/game/')
      && url.includes(`player=${DONOR}`) && url.includes('limit=25')));

    // A transport failure is the same answer.
    globalThis.fetch = async () => { throw new Error('offline'); };
    invalidateJSONCache();
    assert.equal((await readSacrificeHistory(DONOR)).available, false);

    // So is a wallet that is not an address — with no request at all.
    const before = requested.length;
    assert.equal((await readSacrificeHistory('not-an-address')).available, false);
    assert.equal(requested.length, before);

    globalThis.fetch = async () => ({
      ok: true,
      status: 200,
      headers: { get: () => 'application/json' },
      json: async () => ({
        entries: [
          { issuer: CONTRACTS.VAULT, player: DONOR, day: 44, amount: '100', weight: '800', entryIndex: 0 },
          null,
          7,
        ],
        awards: [{ issuer: CONTRACTS.SDGNRS, player: DONOR, day: 43, slot: 1, boonKind: 5, boonType: 5, entryIndex: 0 }],
      }),
      text: async () => '',
    });
    invalidateJSONCache();
    const live = await readSacrificeHistory(DONOR, { limit: 5 });
    assert.equal(live.available, true);
    assert.equal(live.entries.length, 1, 'malformed rows are dropped, not rendered');
    assert.equal(live.awards.length, 1);
  } finally {
    globalThis.fetch = priorFetch;
  }
});

test('a player standing sums their own frozen entries and the three slots draw with replacement', () => {
  const entries = [
    { issuer: CONTRACTS.VAULT, day: 44, amount: '100', weight: '800' },
    { issuer: CONTRACTS.VAULT, day: 44, amount: '900', weight: '21600' },
    { issuer: CONTRACTS.VAULT, day: 43, amount: '500', weight: '4000' },  // another day
    { issuer: CONTRACTS.SDGNRS, day: 44, amount: '300', weight: '2400' }, // the other god
  ];
  const standing = sacrificeStanding(entries, { issuer: CONTRACTS.VAULT, day: 44 });
  assert.deepEqual(standing, { count: 2, weight: 22_400n, amountWei: 1_000n });

  assert.equal(sacrificeStanding(null, {}).count, 0);

  assert.equal(SACRIFICE_SLOTS_PER_POOL, 3);
  // Half the pool, three independent draws: 1 - 0.5^3.
  assert.equal(sacrificeAnySlotChance(50n, 100n).toFixed(4), '0.8750');
  assert.equal(sacrificeAnySlotChance(100n, 100n), 1, 'the only entry wins every slot');
  assert.equal(sacrificeAnySlotChance(0n, 100n), null);
  assert.equal(sacrificeAnySlotChance(10n, 0n), null);
});
