#!/usr/bin/env node

import { readFile, writeFile } from 'node:fs/promises';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { createHash } from 'node:crypto';
import { build } from 'esbuild';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const packagePath = resolve(root, 'node_modules/ethers/package.json');
const outputPath = resolve(root, 'app/vendor/ethers-app.mjs');
const checkOnly = process.argv.includes('--check');
const expectedVersion = '6.17.0';

const packageJson = JSON.parse(await readFile(packagePath, 'utf8'));
if (packageJson.version !== expectedVersion) {
  throw new Error(
    `Expected ethers ${expectedVersion}, found ${packageJson.version}; `
    + 'keep package.json pinned to the browser version before rebuilding.',
  );
}

// Keep this list deliberately small and auditable. It is the union of named
// imports and ethers.* runtime accesses under app/ (tests enforce parity for
// the crypto, ABI, provider and contract surfaces used by the application).
const exports = [
  'AbiCoder',
  'BrowserProvider',
  'Contract',
  'Interface',
  'JsonRpcProvider',
  'LogDescription',
  'ZeroAddress',
  'ZeroHash',
  'decodeBytes32String',
  'encodeBytes32String',
  'formatEther',
  'getAddress',
  'id',
  'isAddress',
  'keccak256',
  'parseEther',
  'solidityPackedKeccak256',
  'toBeHex',
  'version',
  'zeroPadValue',
];
const names = exports.join(', ');
const entry = [
  `import { ${names} } from 'ethers';`,
  `const ethers = Object.freeze({ ${names} });`,
  `export { ${names}, ethers };`,
].join('\n');

const result = await build({
  stdin: {
    contents: entry,
    loader: 'js',
    resolveDir: root,
    sourcefile: 'ethers-app-entry.mjs',
  },
  banner: {
    js: '/* Generated by db/build-ethers-vendor.mjs — do not edit directly. */',
  },
  bundle: true,
  charset: 'utf8',
  format: 'esm',
  legalComments: 'eof',
  minify: true,
  platform: 'browser',
  sourcemap: false,
  target: ['es2022'],
  treeShaking: true,
  write: false,
});

if (result.outputFiles.length !== 1) {
  throw new Error(`Expected one ethers output file, got ${result.outputFiles.length}`);
}
const expected = result.outputFiles[0].contents;
// Device wallets need the complete library. Build it from the same locked npm
// installation so the signer and the slim app bundle cannot drift apart.
const fullResult = await build({
  absWorkingDir: root,
  entryPoints: ['ethers'],
  banner: { js: '/* Generated by db/build-ethers-vendor.mjs — do not edit directly. */' },
  bundle: true,
  charset: 'utf8',
  format: 'esm',
  legalComments: 'eof',
  minify: true,
  platform: 'browser',
  target: ['es2022'],
  write: false,
});
const fullPath = resolve(root, 'app/vendor/ethers.mjs');
const complete = fullResult.outputFiles[0].contents;
const manifestPath = resolve(root, 'app/vendor/MANIFEST.txt');
const manifest = await readFile(manifestPath, 'utf8');
const manifestEntry = `${createHash('sha256').update(complete).digest('hex')}  ethers.mjs  ${complete.length}  https://registry.npmjs.org/ethers/-/ethers-${expectedVersion}.tgz`;

if (checkOnly) {
  let actual = null;
  try { actual = await readFile(outputPath); } catch (_error) { /* reported below */ }
  if (!actual?.equals(expected)) {
    console.error('app/vendor/ethers-app.mjs is stale; run npm run build:vendor');
    process.exitCode = 1;
  }
  const full = await readFile(fullPath).catch(() => null);
  if (!full?.equals(complete) || !manifest.split('\n').includes(manifestEntry)) {
    console.error('Full ethers module or manifest is stale; run npm run build:vendor');
    process.exitCode = 1;
  }
} else {
  await writeFile(outputPath, expected);
  await writeFile(fullPath, complete);
  const entries = manifest.split('\n').filter((line) => line && !line.includes('  ethers.mjs  '));
  await writeFile(manifestPath, `${entries.join('\n')}\n${manifestEntry}\n`);
  const saved = complete.length - expected.length;
  console.log(`ethers ${expectedVersion}: full ${complete.length}, slim ${expected.length} bytes (${saved} bytes saved)`);
}
