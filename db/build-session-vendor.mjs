#!/usr/bin/env node
// Build the tiny crypto bundle the session Pages Function imports.
//
// The handoff proposed rewriting signature verification as `@noble/secp256k1` + hand-rolled
// EIP-191. That is a rewrite of the one thing in this port whose behaviour must not move: the
// old server authenticated wallets with `ethers.verifyMessage`, and any difference in message
// prefixing, hash, or recovery id handling is an authentication bug rather than a test failure.
// ethers is a pinned dependency of this repo and already the browser's signer, so
// vendoring the SAME function keeps verification byte-identical on both sides of the port. The
// tree-shaken surface is three names.
//
//   node db/build-session-vendor.mjs          # build
//   node db/build-session-vendor.mjs --check  # fail if the committed bundle is stale
import { readFile, writeFile } from 'node:fs/promises';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { build } from 'esbuild';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const outputPath = resolve(root, 'functions/session/_vendor/ethers-session.mjs');
const checkOnly = process.argv.includes('--check');
const expectedVersion = '6.17.0';

const packageJson = JSON.parse(await readFile(resolve(root, 'node_modules/ethers/package.json'), 'utf8'));
if (packageJson.version !== expectedVersion) {
  throw new Error(`Expected ethers ${expectedVersion}, found ${packageJson.version}.`);
}

// Deliberately minimal: what the session routes call, and nothing else.
const exports = ['getAddress', 'isAddress', 'verifyMessage'];

const result = await build({
  stdin: {
    contents: `export { ${exports.join(', ')} } from 'ethers';\n`,
    resolveDir: root,
    sourcefile: 'session-vendor-entry.js',
  },
  bundle: true,
  format: 'esm',
  // Workers runtime is browser-like: 'browser' picks ethers' browser field, which swaps the
  // node crypto/http/ws paths that a 'neutral' build cannot resolve.
  platform: 'browser',
  target: 'es2022',
  minify: true,
  legalComments: 'none',
  write: false,
});

const banner = `// Generated by db/build-session-vendor.mjs from ethers ${expectedVersion}; do not hand-edit.\n`;
const output = banner + result.outputFiles[0].text;

if (checkOnly) {
  const current = await readFile(outputPath, 'utf8').catch(() => '');
  if (current !== output) {
    throw new Error('Stale session crypto vendor; run node db/build-session-vendor.mjs');
  }
  console.log(`Verified session crypto vendor (${exports.join(', ')}).`);
} else {
  await writeFile(outputPath, output);
  console.log(`Built session crypto vendor: ${exports.join(', ')} (${(output.length / 1024).toFixed(1)} KiB).`);
}
