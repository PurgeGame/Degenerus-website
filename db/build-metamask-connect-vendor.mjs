#!/usr/bin/env node
import { readFile, writeFile } from 'node:fs/promises';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { build } from 'esbuild';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const outputPath = resolve(root, 'app/vendor/metamask-connect.mjs');
const pkg = JSON.parse(await readFile(resolve(root, 'node_modules/@metamask/connect-evm/package.json'), 'utf8'));
if (pkg.version !== '2.1.1') throw new Error(`Unexpected MetaMask Connect version: ${pkg.version}`);

// MetaMask's own phone connection (its WalletConnect can stop answering while
// this relay keeps working). Lazy-loaded only when a player picks MetaMask on
// a phone, as one same-origin module like the WalletConnect bundle.
const result = await build({
  absWorkingDir: root,
  entryPoints: ['@metamask/connect-evm'],
  bundle: true,
  format: 'esm',
  platform: 'browser',
  target: 'es2022',
  minify: true,
  legalComments: 'eof',
  write: false,
  define: { 'process.env.NODE_ENV': '"production"', global: 'globalThis' },
  banner: { js: '/* Generated by db/build-metamask-connect-vendor.mjs — do not edit directly. */' },
});
const expected = result.outputFiles[0].contents;
if (process.argv.includes('--check')) {
  const actual = await readFile(outputPath).catch(() => null);
  if (!actual?.equals(expected)) {
    console.error('MetaMask Connect bundle is stale; run npm run build:vendor');
    process.exitCode = 1;
  }
} else {
  await writeFile(outputPath, expected);
  console.log(`MetaMask Connect ${pkg.version}: ${expected.length} bytes, one lazy module`);
}
