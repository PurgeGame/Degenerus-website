#!/usr/bin/env bash
# Vendor the browser's npm dependencies into app/vendor/ — no build step.
#
# WHY THIS EXISTS
# ---------------
# The site ships plain ES modules with no bundler, so npm packages reach the
# browser through an import map. Those entries used to point at esm.sh, a free
# public CDN that compiles npm packages to browser modules on demand. That put a
# third party on the critical path of every page load: if esm.sh is slow, down,
# or serves a bad build, the app does not boot — and whatever it returns runs
# with full page privileges.
#
# esm.sh can emit each package as ONE self-contained file (`?bundle`), which is
# what this script captures. The import map then points at local paths, the
# bytes come from our own edge, and the no-build architecture is untouched:
# these are static files, not a bundler step.
#
# It also removes 46 cold-load requests (25 for ethers itself, 19 for its
# @noble crypto dependencies) in favour of 4 same-origin ones.
#
# Ethers is built from the locked npm installation by build-ethers-vendor.mjs.
# Wallet connectors have their own npm bundle builders in npm run build:vendor.
#
# USAGE
#   ./db/vendor-modules.sh          # fetch + write app/vendor/ + print manifest
#   ./db/vendor-modules.sh --check  # verify on-disk files match the manifest
#
# To upgrade a package: bump the version below, re-run, re-measure, republish.
set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
VENDOR="$ROOT/app/vendor"
MANIFEST="$VENDOR/MANIFEST.txt"
MODE="${1:-fetch}"

# name<TAB>esm.sh specifier<TAB>local filename
# Versions are pinned exactly; the import map pinned them already, so vendoring
# changes where the bytes come from, not which bytes.
PACKAGES=$(cat <<'EOF'
gsap	gsap@3.14	gsap.mjs
gsap-Flip	gsap@3.14/Flip	gsap-flip.mjs
gsap-TextPlugin	gsap@3.14/TextPlugin	gsap-textplugin.mjs
lean-qr	lean-qr@2.5	lean-qr.mjs
EOF
)

if [ "$MODE" = "--check" ]; then
  node "$ROOT/db/build-ethers-vendor.mjs" --check
  fail=0
  while IFS=$'\t' read -r name spec file; do
    [ -z "$name" ] && continue
    want=$(grep -F "  $file  " "$MANIFEST" 2>/dev/null | awk '{print $1}')
    got=$(sha256sum "$VENDOR/$file" 2>/dev/null | awk '{print $1}')
    if [ -z "$got" ]; then echo "MISSING: $file"; fail=1
    elif [ "$want" != "$got" ]; then echo "SHA MISMATCH: $file"; fail=1
    fi
  done <<< "$PACKAGES"
  [ "$fail" = 0 ] && echo "vendor/ matches MANIFEST.txt" || exit 1
  exit 0
fi

mkdir -p "$VENDOR"
tmp_manifest="$(mktemp)"
{
  echo "# Vendored browser modules — generated by db/vendor-modules.sh"
  echo "# Sources: pinned npm for ethers; esm.sh bundles for the remaining modules."
  echo "# sha256  file  bytes  source-url"
} > "$tmp_manifest"

while IFS=$'\t' read -r name spec file; do
  [ -z "$name" ] && continue
  # The `?bundle` URL returns a tiny shim re-exporting the real bundle path;
  # follow it so we store the actual self-contained module, not the shim.
  shim=$(curl -fsSL --max-time 60 "https://esm.sh/${spec}?bundle")
  inner=$(printf '%s' "$shim" | grep -oE '"/[^"]+"' | tr -d '"' | head -1)
  if [ -z "$inner" ]; then
    echo "ERROR: no bundle path for $spec — it may not collapse to one file" >&2
    exit 1
  fi
  curl -fsSL --max-time 180 "https://esm.sh${inner}" -o "$VENDOR/$file"

  # A vendored file that still reaches out defeats the entire point.
  ext=$(grep -oE 'from"[^"]+"|import"[^"]+"' "$VENDOR/$file" | grep -cE '"(https?:)?/' || true)
  if [ "${ext:-0}" -ne 0 ]; then
    echo "ERROR: $file still has $ext external imports — not self-contained" >&2
    exit 1
  fi

  sha=$(sha256sum "$VENDOR/$file" | awk '{print $1}')
  bytes=$(wc -c < "$VENDOR/$file")
  printf '%s  %s  %s  https://esm.sh%s\n' "$sha" "$file" "$bytes" "$inner" >> "$tmp_manifest"
  printf '  %-22s %8s bytes  %s\n' "$name" "$bytes" "$file"
done <<< "$PACKAGES"

mv "$tmp_manifest" "$MANIFEST"
# mktemp gives 600; the manifest is published alongside the modules.
chmod 644 "$MANIFEST"
node "$ROOT/db/build-ethers-vendor.mjs"
echo "wrote $MANIFEST"
