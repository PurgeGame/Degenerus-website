#!/usr/bin/env node
import { readFile, writeFile } from 'node:fs/promises';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { build } from 'esbuild';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const outputPath = resolve(root, 'app/vendor/walletconnect.mjs');
const pkg = JSON.parse(await readFile(resolve(root, 'node_modules/@walletconnect/ethereum-provider/package.json'), 'utf8'));
if (pkg.version !== '2.23.9') throw new Error(`Unexpected WalletConnect version: ${pkg.version}`);

// The provider remains lazy-loaded on connect/restore. Bundle its dependency
// graph into one same-origin request so mobile connections do not wait for
// hundreds of separate CDN modules before they can show the wallet picker.
const result = await build({
  absWorkingDir: root,
  entryPoints: ['@walletconnect/ethereum-provider'],
  bundle: true,
  format: 'esm',
  platform: 'browser',
  target: 'es2022',
  minify: true,
  legalComments: 'eof',
  write: false,
  banner: { js: '/* Generated by db/build-walletconnect-vendor.mjs — do not edit directly. */' },
});
const expected = result.outputFiles[0].contents;
if (process.argv.includes('--check')) {
  const actual = await readFile(outputPath).catch(() => null);
  if (!actual?.equals(expected)) {
    console.error('WalletConnect bundle is stale; run npm run build:vendor');
    process.exitCode = 1;
  }
} else {
  await writeFile(outputPath, expected);
  console.log(`WalletConnect ${pkg.version}: ${expected.length} bytes, one lazy module`);
}
