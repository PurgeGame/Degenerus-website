#!/usr/bin/env node
import { readFile, writeFile } from 'node:fs/promises';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { build } from 'esbuild';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const outputPath = resolve(root, 'app/vendor/coinbase-wallet.mjs');
const pkg = JSON.parse(await readFile(resolve(root, 'node_modules/@coinbase/wallet-sdk/package.json'), 'utf8'));
if (pkg.version !== '4.4.0') throw new Error(`Unexpected Coinbase Wallet SDK version: ${pkg.version}`);

// Coinbase Smart Wallet: the passkey wallet for players with no wallet yet
// (no app, no extension; Ethereum Sepolia is a supported network). Lazy-loaded
// only when the no-wallet option is offered, as one same-origin module like
// the WalletConnect and MetaMask Connect bundles.
const result = await build({
  absWorkingDir: root,
  entryPoints: ['@coinbase/wallet-sdk'],
  bundle: true,
  format: 'esm',
  platform: 'browser',
  target: 'es2022',
  minify: true,
  legalComments: 'eof',
  write: false,
  define: { 'process.env.NODE_ENV': '"production"', global: 'globalThis' },
  banner: { js: '/* Generated by db/build-coinbase-wallet-vendor.mjs — do not edit directly. */' },
});
const expected = result.outputFiles[0].contents;
if (process.argv.includes('--check')) {
  const actual = await readFile(outputPath).catch(() => null);
  if (!actual?.equals(expected)) {
    console.error('Coinbase Wallet bundle is stale; run npm run build:vendor');
    process.exitCode = 1;
  }
} else {
  await writeFile(outputPath, expected);
  console.log(`Coinbase Wallet SDK ${pkg.version}: ${expected.length} bytes, one lazy module`);
}
